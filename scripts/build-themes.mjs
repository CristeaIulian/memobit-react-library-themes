// Compiles each theme to its own stylesheet and extracts the handful of colours the
// theme picker needs to draw a preview.
//
// Themes used to ship as one 625 KB aggregate that every app imported wholesale, though
// only one is ever active. Emitting them separately lets an app fetch the one it is using
// and nothing else. The picker still lists all 64, so it gets a generated palette instead
// — six colours per theme is enough to draw a swatch, and costs ~6 KB for the whole set
// rather than the stylesheets themselves.

import { mkdirSync, readdirSync, writeFileSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { format, resolveConfig } from 'prettier';
import * as sass from 'sass';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const themingDir = join(root, 'src/theming');
const distDir = join(root, 'dist');
const themesOutDir = join(distDir, 'themes');

// Exactly the tokens ThemeSettings.scss reads to render a preview swatch.
const PREVIEW_TOKENS = [
    '--body-background',
    '--body-accent-color',
    '--body-color-muted',
    '--card-background-color',
    '--header-background-color',
    '--header-border-bottom-color',
];

// Follows var(--a, var(--b)) chains back to a colour. Themes built through the
// _profile-theme mixin never declare --body-background literally: it is always an
// indirection onto --body-background-base, which the mixin sets.
const resolveLiteral = (css, value, seen = new Set()) => {
    if (!value.includes('var(')) {
        return value;
    }

    const reference = value.match(/var\(\s*(--[a-z0-9-]+)\s*(?:,\s*([\s\S]+))?\)$/i);

    if (reference === null) {
        return null;
    }

    const [, token, fallback] = reference;

    if (!seen.has(token)) {
        seen.add(token);

        const declared = [...css.matchAll(new RegExp(`${token}s*:s*([^;}]+)`, 'g'))].map(match => match[1].trim());
        const direct = declared.filter(candidate => !candidate.includes('var(')).pop();

        if (direct !== undefined) {
            return direct;
        }

        for (const candidate of declared.reverse()) {
            const resolved = resolveLiteral(css, candidate, seen);

            if (resolved !== null) {
                return resolved;
            }
        }
    }

    return fallback === undefined ? null : resolveLiteral(css, fallback.trim(), seen);
};

const themeNames = readdirSync(themingDir)
    .filter(file => file.endsWith('.scss') && !file.startsWith('_'))
    .map(file => file.slice(0, -5))
    .sort();

mkdirSync(themesOutDir, { recursive: true });

const palettes = {};

for (const name of themeNames) {
    const { css } = sass.compile(join(themingDir, `${name}.scss`), {
        style: 'compressed',
        silenceDeprecations: ['legacy-js-api'],
    });

    writeFileSync(join(themesOutDir, `${name}.css`), `${css}\n`);

    const palette = {};

    for (const token of PREVIEW_TOKENS) {
        const values = [...css.matchAll(new RegExp(`${token}s*:s*([^;}]+)`, 'g'))].map(match => match[1].trim());

        // Take the last LITERAL value, not simply the last one. Nearly every theme declares
        // --body-background as a colour and then re-declares it as
        // var(--body-background-wash, var(--body-background-base)) so it can be overridden at
        // runtime. That indirection resolves fine inside the themed document, but a preview
        // swatch is drawn from these values alone, where the referenced tokens do not exist.
        const literal = values.filter(value => !value.includes('var(')).pop() ?? resolveLiteral(css, values[values.length - 1] ?? '');

        if (literal !== undefined && literal !== null) {
            palette[token] = literal;
        }
    }

    const missing = PREVIEW_TOKENS.filter(token => !(token in palette));

    if (missing.length > 0) {
        throw new Error(`Theme "${name}" is missing preview tokens: ${missing.join(', ')}`);
    }

    palettes[name] = palette;
}

// The aggregate stays published so an app that has not migrated keeps working.
const aggregate = sass.compile(join(root, 'src/themes.scss'), {
    style: 'compressed',
    silenceDeprecations: ['legacy-js-api'],
});
writeFileSync(join(distDir, 'themes.css'), `${aggregate.css}\n`);

const entries = Object.entries(palettes)
    .map(([name, palette]) => {
        const tokens = Object.entries(palette)
            .map(([token, value]) => `        '${token}': ${JSON.stringify(value)},`)
            .join('\n');

        return `    '${name}': {\n${tokens}\n    },`;
    })
    .join('\n');

const previewPalettesPath = join(root, 'src/previewPalettes.ts');
const previewPalettesSource = `// AUTO-GENERATED by scripts/build-themes.mjs — do not edit by hand.
//
// The few colours the theme picker needs to draw a swatch for a theme whose stylesheet is
// not loaded. Compiled from each theme rather than read from source, because ten themes
// build their tokens through the _profile-theme mixin.

export type PreviewToken =
${PREVIEW_TOKENS.map(token => `    | '${token}'`).join('\n')};

export const previewPalettes: Readonly<Record<string, Readonly<Record<PreviewToken, string>>>> = {
${entries}
};
`;

// Run through the shared Prettier config so a build never leaves the file unformatted.
const prettierConfig = await resolveConfig(previewPalettesPath);
writeFileSync(previewPalettesPath, await format(previewPalettesSource, { ...prettierConfig, filepath: previewPalettesPath }));

console.log(`Compiled ${themeNames.length} themes to dist/themes/`);
console.log(`Wrote preview palettes for ${Object.keys(palettes).length} themes`);
